// DBHub process helpers for the mssql-data plugin: the generated configuration, the command
// that starts DBHub on each platform, and a one-shot query used to test a server.
import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { passwordEnvVar } from "./lib.mjs";

export const DBHUB_PACKAGE = "@bytebase/dbhub@1.5.0";

const MAX_ROWS = 1000;
const CONNECTION_TIMEOUT_SECONDS = 30;
const QUERY_TIMEOUT_SECONDS = 60;
const PROTOCOL_VERSION = "2025-03-26";
const STDERR_TAIL_CHARS = 1500;
const EXIT_GRACE_MS = 3000;

// JSON string escapes are valid TOML basic-string escapes, and inputs are validated in lib.mjs.
const toml = (value) => JSON.stringify(String(value));

/**
 * SQL Server DSN with no database in the path, so the connection opens the login's
 * default database. The password is a placeholder that DBHub fills from the environment.
 */
function buildDsn(server) {
  const params = new URLSearchParams([
    ["sslmode", server.sslmode],
    ...(server.instance ? [["instanceName", server.instance]] : []),
    ...(server.auth === "ntlm" ? [["authentication", "ntlm"], ["domain", server.domain]] : []),
  ]);
  return `sqlserver://${encodeURIComponent(server.user)}:\${${passwordEnvVar(server.id)}}@${server.host}:${server.port}/?${params}`;
}

/** DBHub TOML for the given servers: one read-only source with four tools per server. */
export function buildDbhubToml(servers) {
  const sources = servers.flatMap((server) => [
    "[[sources]]",
    `id = ${toml(server.id)}`,
    ...(server.description ? [`description = ${toml(server.description)}`] : []),
    `dsn = ${toml(buildDsn(server))}`,
    `connection_timeout = ${CONNECTION_TIMEOUT_SECONDS}`,
    `query_timeout = ${QUERY_TIMEOUT_SECONDS}`,
    "lazy = true",
    "",
  ]);
  const tools = servers.flatMap((server) => [
    "[[tools]]",
    'name = "execute_sql"',
    `source = ${toml(server.id)}`,
    "readonly = true",
    `max_rows = ${MAX_ROWS}`,
    "",
    ...["search_objects", "explain_sql", "health_check"].flatMap((name) => [
      "[[tools]]",
      `name = "${name}"`,
      `source = ${toml(server.id)}`,
      "",
    ]),
  ]);
  return ["# Generated by the mssql-data plugin from servers.json. Do not edit.", "", ...sources, ...tools].join("\n");
}

/** Writes the DBHub configuration for these servers to a private temp folder. */
export function writeDbhubConfig(servers) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "mssql-data-"));
  const file = path.join(dir, "dbhub.toml");
  fs.writeFileSync(file, buildDbhubToml(servers), { mode: 0o600 });
  return { file, cleanup: () => fs.rmSync(dir, { recursive: true, force: true }) };
}

/** Process environment that hands each server's URL-encoded password to DBHub. */
export function dbhubEnv(serversWithSecrets, baseEnv = process.env) {
  return {
    ...baseEnv,
    ...Object.fromEntries(serversWithSecrets.map(({ server, secret }) => [passwordEnvVar(server.id), encodeURIComponent(secret)])),
  };
}

const quoteForCmd = (arg) => `"${arg.replace(/"/g, '""')}"`;

export function dbhubCommand(config) {
  const args = ["-y", DBHUB_PACKAGE, "--transport", "stdio", "--config", config];
  if (process.platform !== "win32") return { command: "npx", args, shell: false };
  // npx is a .cmd shim on Windows, which Node only starts through a shell. Run npm's npx
  // script with this Node binary instead, and fall back to the shim when it is elsewhere.
  const npxCli = path.join(path.dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js");
  if (fs.existsSync(npxCli)) return { command: process.execPath, args: [npxCli, ...args], shell: false };
  return { command: "npx.cmd", args: args.map(quoteForCmd), shell: true };
}

const stderrTail = (text) => (text.trim() ? `\n${text.trim().slice(-STDERR_TAIL_CHARS)}` : "");

function parseExecuteResult(message) {
  const text = message.result?.content?.[0]?.text ?? "";
  let payload;
  try {
    payload = JSON.parse(text);
  } catch {
    return { ok: false, error: text || JSON.stringify(message.error ?? message.result) };
  }
  if (message.result?.isError || payload.success === false) return { ok: false, error: payload.error ?? text };
  return { ok: true, rows: payload.data?.statements?.[0]?.rows ?? [] };
}

/**
 * Starts DBHub for one server, runs one read-only query through execute_sql, and stops it.
 * Resolves to { ok: true, rows } or { ok: false, error }; rejects when DBHub itself fails.
 */
export function queryServer(server, secret, sql, { timeoutMs }) {
  return new Promise((resolve, reject) => {
    const config = writeDbhubConfig([server]);
    const { command, args, shell } = dbhubCommand(config.file);
    const child = spawn(command, args, { env: dbhubEnv([{ server, secret }]), stdio: ["pipe", "pipe", "pipe"], shell, windowsHide: true });
    let stderr = "";
    let buffer = "";
    let settled = false;
    const settle = (callback) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      // Closing stdin makes DBHub exit on its own; the kill only covers a hung process.
      child.stdin.end();
      setTimeout(() => child.kill(), EXIT_GRACE_MS).unref();
      callback();
    };
    const timer = setTimeout(
      () => settle(() => reject(new Error(`DBHub tidak merespons dalam ${Math.round(timeoutMs / 1000)} detik.${stderrTail(stderr)}`))),
      timeoutMs,
    );
    const send = (message) => child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", ...message })}\n`);
    // DBHub may exit before reading everything we wrote; the exit handler reports that case.
    child.stdin.on("error", () => {});
    child.stderr.setEncoding("utf8");
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.stdout.setEncoding("utf8");
    child.stdout.on("data", (chunk) => {
      const lines = (buffer + chunk).split("\n");
      buffer = lines.pop();
      for (const line of lines) {
        let message;
        try {
          message = JSON.parse(line);
        } catch {
          continue;
        }
        if (message.id === 1) {
          send({ method: "notifications/initialized" });
          send({ id: 2, method: "tools/call", params: { name: "execute_sql", arguments: { sql } } });
        } else if (message.id === 2) {
          settle(() => resolve(parseExecuteResult(message)));
        }
      }
    });
    child.on("error", (error) => settle(() => reject(new Error(`DBHub tidak bisa dijalankan: ${error.message}`))));
    child.on("exit", (code) => {
      config.cleanup();
      settle(() => reject(new Error(`DBHub berhenti sebelum menjawab (kode ${code}).${stderrTail(stderr)}`)));
    });
    send({ id: 1, method: "initialize", params: { protocolVersion: PROTOCOL_VERSION, capabilities: {}, clientInfo: { name: "mssql-data-test", version: "1" } } });
  });
}
